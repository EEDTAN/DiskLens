const { contextBridge, ipcRenderer } = require('electron');

const inv = channel => (...args) => ipcRenderer.invoke(channel, ...args);

contextBridge.exposeInMainWorld('api', {
  drives: inv('drives:list'),
  paths: inv('app:paths'),
  version: inv('app:version'),
  langs: inv('i18n:all'),
  getSettings: inv('settings:get'),
  setSettings: inv('settings:set'),
  pickFolder: inv('dialog:folder'),
  scan: inv('scan:start'),
  cancelScan: inv('scan:cancel'),
  list: inv('fs:list'),
  stat: inv('fs:stat'),
  size: inv('fs:size'),
  thumb: inv('fs:thumb'),
  open: inv('shell:open'),
  show: inv('shell:show'),
  external: inv('shell:external'),
  copy: inv('clipboard:write'),
  analysis: inv('analysis:run'),
  classifyMany: inv('analysis:classifyMany'),
  guard: inv('ops:guard'),
  verinfo: inv('fs:verinfo'),
  oldFiles: inv('old:list'),
  typeFiles: inv('type:list'),
  dupsStart: inv('dups:start'),
  dupsCancel: inv('dups:cancel'),
  runOp: inv('ops:run'),
  cancelOp: inv('ops:cancel'),
  pickDest: inv('dialog:dest'),
  free: inv('fs:free'),
  emptyBin: inv('recycle:empty'),
  scanInfo: inv('scan:info'),
  updState: inv('update:state'),
  updCheck: inv('update:check'),
  updDownload: inv('update:download'),
  updInstall: inv('update:install'),
  updPage: inv('update:page'),
  onUpdate: cb => ipcRenderer.on('update:state', (_, d) => cb(d)),
  onDupsProgress: cb => ipcRenderer.on('dups:progress', (_, d) => cb(d)),
  onDupsDone: cb => ipcRenderer.on('dups:done', (_, d) => cb(d)),
  onOpProgress: cb => ipcRenderer.on('ops:progress', (_, d) => cb(d)),
  onProgress: cb => ipcRenderer.on('scan:progress', (_, d) => cb(d)),
  onDone: cb => ipcRenderer.on('scan:done', (_, d) => cb(d)),
});
